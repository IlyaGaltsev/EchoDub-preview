let syncDemoVideoLabels = () => {};

function detectLang() {
  const params = new URLSearchParams(location.search).get("lang");
  if (params === "en" || params === "ru") return params;
  const saved = localStorage.getItem("echodub-lang");
  if (saved === "en" || saved === "ru") return saved;
  return (navigator.language || "").toLowerCase().startsWith("en") ? "en" : "ru";
}

function applyLang(lang) {
  const pack = I18N[lang] || I18N.ru;
  document.documentElement.lang = lang;
  document.documentElement.dataset.lang = lang;
  localStorage.setItem("echodub-lang", lang);
  const url = new URL(location.href);
  if (url.searchParams.has("lang") && url.searchParams.get("lang") !== lang) {
    url.searchParams.set("lang", lang);
    history.replaceState({}, "", url);
  }

  if (document.body.classList.contains("page-legal") && pack["privacy.title"]) {
    document.title = pack["privacy.title"];
  } else if (document.body.classList.contains("page-support") && pack["support.title"]) {
    document.title = pack["support.title"];
  } else if (pack.title) {
    document.title = pack.title;
  }
  const meta = document.querySelector('meta[name="description"]');
  if (meta && pack.description) meta.setAttribute("content", pack.description);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = pack[node.getAttribute("data-i18n")];
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-href]").forEach((node) => {
    const value = pack[node.getAttribute("data-i18n-href")];
    if (value) node.setAttribute("href", value);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    const value = pack[node.getAttribute("data-i18n-aria")];
    if (value) node.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const value = pack[node.getAttribute("data-i18n-placeholder")];
    if (value) node.setAttribute("placeholder", value);
  });
  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    button.setAttribute(
      "aria-pressed",
      button.getAttribute("data-set-lang") === lang ? "true" : "false"
    );
  });
  syncDemoVideoLabels();
}

const jump = new URLSearchParams(location.search).get("jump");
if (jump) {
  document.documentElement.style.scrollBehavior = "auto";
  const node = document.getElementById(jump);
  if (node) node.scrollIntoView();
}

applyLang(detectLang());

const supportNext = document.querySelector("[data-support-next]");
if (supportNext) {
  const next = new URL(location.href);
  next.search = "";
  next.hash = "";
  next.searchParams.set("sent", "1");
  supportNext.value = next.toString();
}

if (document.body.classList.contains("page-support")) {
  const params = new URLSearchParams(location.search);
  if (params.get("sent") === "1") {
    const toast = document.getElementById("sent");
    if (toast) toast.hidden = false;
    params.delete("sent");
    const clean = `${location.pathname}${params.toString() ? `?${params}` : ""}${location.hash}`;
    history.replaceState({}, "", clean);
  }
}

document.addEventListener("click", (event) => {
  const button = event.target.closest("[data-set-lang]");
  if (!button) return;
  applyLang(button.getAttribute("data-set-lang"));
});

const video = document.querySelector("[data-demo-video]");
if (video) {
  const soundBtn = document.querySelector("[data-video-sound]");
  const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  function pack() {
    return I18N[document.documentElement.lang] || I18N.ru;
  }

  function syncSoundLabel() {
    const muted = video.muted;
    const key = muted ? "demo.unmute" : "demo.mute";
    const label = pack()[key];
    soundBtn.setAttribute("aria-label", label);
    soundBtn.setAttribute("aria-pressed", muted ? "false" : "true");
    soundBtn.setAttribute("data-i18n-aria", key);
  }

  function play() {
    return video.play().catch(() => {});
  }

  soundBtn.addEventListener("click", () => {
    video.muted = !video.muted;
    if (!video.muted && video.paused) play();
    syncSoundLabel();
  });

  syncDemoVideoLabels = syncSoundLabel;
  syncSoundLabel();

  if (!reduced) play();
}
